@pytest.mark.django_db
class TestCBORAttestationParsing:
    """Challenge CBOR parsing against authentic browser formats and hostile inputs."""

    def test_browser_attestation_format_none_and_subsequent_assertion(self, crypto_user_setup):
        """Browser CBOR map with fmt='none' unpacks authData and correctly registers uncompressed EC point."""
        user = crypto_user_setup["user"]
        priv_key = crypto_user_setup["private_key"]
        pub_point = crypto_user_setup["public_point"]

        x_bytes = pub_point[0].to_bytes(32, "big")
        y_bytes = pub_point[1].to_bytes(32, "big")
        cose_key = {1: 2, 3: -7, -1: 1, -2: x_bytes, -3: y_bytes}
        cose_bytes = cbor_encode(cose_key)

        rp_hash = hashlib.sha256(b"localhost").digest()
        cred_id = b64url_encode(secrets.token_bytes(24))
        cred_id_bytes = b64url_decode(cred_id)
        auth_data = (
            rp_hash
            + bytes([0x41])  # UP | AT
            + struct.pack(">I", 0)
            + bytes(16)
            + struct.pack(">H", len(cred_id_bytes))
            + cred_id_bytes
            + cose_bytes
        )

        att_obj = {"fmt": "none", "attStmt": {}, "authData": auth_data}
        chal = b64url_encode(secrets.token_bytes(32))
        client_data = {"type": "webauthn.create", "challenge": chal, "origin": "http://testserver"}

        reg_payload = {
            "id": cred_id,
            "rawId": cred_id,
            "type": "public-key",
            "response": {
                "clientDataJSON": b64url_encode(json.dumps(client_data).encode("utf-8")),
                "attestationObject": b64url_encode(cbor_encode(att_obj)),
            },
        }

        res = verify_registration_response(reg_payload, chal, "localhost", user, "http://testserver")
        assert res["credential_id"] == cred_id
        extracted_point = b64url_decode(res["public_key"])
        assert len(extracted_point) == 65
        assert extracted_point[0] == 0x04
        assert extracted_point[1:33] == x_bytes
        assert extracted_point[33:65] == y_bytes

        # Save credential and verify assertion works with extracted key
        new_cred = PasskeyCredential.objects.create(
            user=user,
            credential_id=cred_id,
            public_key=res["public_key"],
            sign_count=0,
        )
        auth_chal = b64url_encode(secrets.token_bytes(32))
        assertion = build_mock_assertion_payload(
            credential_id=new_cred.credential_id,
            challenge=auth_chal,
            sign_count=1,
            private_key=priv_key,
        )
        auth_res = verify_authentication_response(assertion, auth_chal, "localhost", "http://testserver")
        assert auth_res["user"] == user
        new_cred.refresh_from_db()
        assert new_cred.sign_count == 1

    def test_browser_attestation_format_packed(self, crypto_user_setup):
        """Browser CBOR map with fmt='packed' unpacks authData and matches public key."""
        user = crypto_user_setup["user"]
        pub_point = crypto_user_setup["public_point"]

        x_bytes = pub_point[0].to_bytes(32, "big")
        y_bytes = pub_point[1].to_bytes(32, "big")
        cose_key = {1: 2, 3: -7, -1: 1, -2: x_bytes, -3: y_bytes}
        cose_bytes = cbor_encode(cose_key)

        rp_hash = hashlib.sha256(b"localhost").digest()
        cred_id = "packed-browser-cred-id"
        cred_id_bytes = cred_id.encode("utf-8")
        auth_data = (
            rp_hash
            + bytes([0x41])
            + struct.pack(">I", 0)
            + bytes(16)
            + struct.pack(">H", len(cred_id_bytes))
            + cred_id_bytes
            + cose_bytes
        )

        att_obj = {"fmt": "packed", "attStmt": {"alg": -7, "sig": b"mock_sig"}, "authData": auth_data}
        chal = b64url_encode(secrets.token_bytes(32))
        client_data = {"type": "webauthn.create", "challenge": chal, "origin": "http://testserver"}

        reg_payload = {
            "id": cred_id,
            "type": "public-key",
            "response": {
                "clientDataJSON": b64url_encode(json.dumps(client_data).encode("utf-8")),
                "attestationObject": b64url_encode(cbor_encode(att_obj)),
            },
        }

        res = verify_registration_response(reg_payload, chal, "localhost", user, "http://testserver")
        extracted_point = b64url_decode(res["public_key"])
        assert len(extracted_point) == 65
        assert extracted_point[0] == 0x04

    def test_cbor_attestation_rp_id_hash_mismatch_rejected(self, crypto_user_setup):
        """Attestation with RP ID hash bound to phishing domain is rejected."""
        user = crypto_user_setup["user"]
        evil_rp_hash = hashlib.sha256(b"attacker-domain.com").digest()
        auth_data = evil_rp_hash + bytes([0x41]) + struct.pack(">I", 0) + bytes(16) + struct.pack(">H", 5) + b"12345"

        att_obj = {"fmt": "none", "attStmt": {}, "authData": auth_data}
        chal = b64url_encode(secrets.token_bytes(32))
        client_data = {"type": "webauthn.create", "challenge": chal, "origin": "http://testserver"}

        reg_payload = {
            "id": "evil-rp-cred",
            "type": "public-key",
            "response": {
                "clientDataJSON": b64url_encode(json.dumps(client_data).encode("utf-8")),
                "attestationObject": b64url_encode(cbor_encode(att_obj)),
            },
        }

        with pytest.raises(ValueError, match="RP ID hash mismatch"):
            verify_registration_response(reg_payload, chal, "localhost", user, "http://testserver")

    def test_cbor_malformed_byte_streams_gracefully_rejected(self, crypto_user_setup):
        """Malformed or truncated CBOR attestationObject does not crash the server."""
        user = crypto_user_setup["user"]
        chal = b64url_encode(secrets.token_bytes(32))

        corrupt_streams = [
            b"",
            b"\xa3\x63fmt",
            b"\x58\xff\x01\x02",
            b"\x1f",
            b"\xff\xff\xff",
        ]
        for bad_bytes in corrupt_streams:
            reg_payload = {
                "id": "bad-cbor-cred",
                "type": "public-key",
                "response": {
                    "clientDataJSON": b64url_encode(json.dumps({"type": "webauthn.create", "challenge": chal, "origin": "http://testserver"}).encode()),
                    "attestationObject": b64url_encode(bad_bytes),
                },
            }
            with pytest.raises(ValueError):
                verify_registration_response(reg_payload, chal, "localhost", user, "http://testserver")


