@pytest.mark.django_db
class TestForgeryResistance:
    """Challenge signature verification against fabricated, foreign, tampered, and missing signatures."""

    def test_forged_signature_fabricated_string_rejected(self, crypto_user_setup):
        """Completely fabricated signature string is strictly rejected with HTTP 400."""
        client = Client()
        opt_resp = client.post(reverse("auth:webauthn_login_options"), data=json.dumps({}), content_type="application/json")
        server_chal = opt_resp.json()["challenge"]

        payload = build_mock_assertion_payload(
            credential_id=crypto_user_setup["credential"].credential_id,
            challenge=server_chal,
            sign_count=11,
            private_key=crypto_user_setup["private_key"],
        )
        # Fabricate signature
        payload["response"]["signature"] = b64url_encode(b"completely_fabricated_signature_bytes_1234567890")

        resp = client.post(
            reverse("auth:webauthn_login_verify"),
            data=json.dumps({"credential": payload}),
            content_type="application/json",
        )
        assert resp.status_code == 400
        assert "signature" in resp.json().get("error", "").lower()

    def test_forged_signature_different_private_key_rejected(self, crypto_user_setup):
        """Valid signature generated by a different private key is strictly rejected."""
        client = Client()
        opt_resp = client.post(reverse("auth:webauthn_login_options"), data=json.dumps({}), content_type="application/json")
        server_chal = opt_resp.json()["challenge"]

        foreign_priv_key = secrets.randbelow(1000000000) + 999999
        payload = build_mock_assertion_payload(
            credential_id=crypto_user_setup["credential"].credential_id,
            challenge=server_chal,
            sign_count=11,
            private_key=foreign_priv_key,  # Sign with attacker's private key
        )

        resp = client.post(
            reverse("auth:webauthn_login_verify"),
            data=json.dumps({"credential": payload}),
            content_type="application/json",
        )
        assert resp.status_code == 400
        assert "signature" in resp.json().get("error", "").lower()

    def test_tampered_challenge_with_old_signature_rejected(self, crypto_user_setup):
        """Tampering challenge in clientDataJSON while retaining genuine signature fails verification."""
        client = Client()
        opt_resp = client.post(reverse("auth:webauthn_login_options"), data=json.dumps({}), content_type="application/json")
        server_chal = opt_resp.json()["challenge"]

        # Valid payload for original challenge
        payload = build_mock_assertion_payload(
            credential_id=crypto_user_setup["credential"].credential_id,
            challenge=server_chal,
            sign_count=11,
            private_key=crypto_user_setup["private_key"],
        )

        # Tamper challenge in clientDataJSON
        cd = json.loads(b64url_decode(payload["response"]["clientDataJSON"]).decode("utf-8"))
        cd["challenge"] = b64url_encode(secrets.token_bytes(32))
        payload["response"]["clientDataJSON"] = b64url_encode(json.dumps(cd).encode("utf-8"))

        resp = client.post(
            reverse("auth:webauthn_login_verify"),
            data=json.dumps({"credential": payload}),
            content_type="application/json",
        )
        assert resp.status_code == 400
        assert "challenge" in resp.json().get("error", "").lower()

    def test_missing_signature_field_rejected(self, crypto_user_setup):
        """Assertion missing a signature field is rejected with HTTP 400 Bad Request."""
        client = Client()
        opt_resp = client.post(reverse("auth:webauthn_login_options"), data=json.dumps({}), content_type="application/json")
        server_chal = opt_resp.json()["challenge"]

        payload = build_mock_assertion_payload(
            credential_id=crypto_user_setup["credential"].credential_id,
            challenge=server_chal,
            sign_count=11,
            private_key=crypto_user_setup["private_key"],
        )
        del payload["response"]["signature"]

        resp = client.post(
            reverse("auth:webauthn_login_verify"),
            data=json.dumps({"credential": payload}),
            content_type="application/json",
        )
        assert resp.status_code == 400
        assert "missing signature" in resp.json().get("error", "").lower()

    def test_tampered_authenticator_data_rejected(self, crypto_user_setup):
        """Modifying any bit of authenticatorData (e.g. sign count or flags) breaks cryptographic verification."""
        chal = b64url_encode(secrets.token_bytes(32))
        payload = build_mock_assertion_payload(
            credential_id=crypto_user_setup["credential"].credential_id,
            challenge=chal,
            sign_count=11,
            private_key=crypto_user_setup["private_key"],
        )

        raw_ad = bytearray(b64url_decode(payload["response"]["authenticatorData"]))
        raw_ad[32] = raw_ad[32] ^ 0x04  # Flip an unused flag bit
        payload["response"]["authenticatorData"] = b64url_encode(bytes(raw_ad))

        with pytest.raises(ValueError, match="Invalid WebAuthn assertion signature"):
            verify_authentication_response(payload, chal, "localhost", "http://testserver")


