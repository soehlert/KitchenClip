# 3. ECDSA Pure-Python Mathematical Invariants
# ==============================================================================

class TestECDSAMathematicalInvariants:
    """Stress test pure-Python P-256 arithmetic against boundary conditions and invalid points."""

    def test_ecdsa_r_zero_or_s_zero_rejected(self):
        """Signatures with r=0 or s=0 evaluate to False."""
        pub_key = _scalar_mul(12345, P256_G)
        assert pub_key is not None
        msg = b"message to verify"

        sig_r0 = b"\x30\x06\x02\x01\x00\x02\x01\x01"
        assert verify_ecdsa_p256_signature(pub_key, msg, sig_r0) is False

        sig_s0 = b"\x30\x06\x02\x01\x01\x02\x01\x00"
        assert verify_ecdsa_p256_signature(pub_key, msg, sig_s0) is False

    def test_ecdsa_r_or_s_greater_than_order_rejected(self):
        """Signatures with r >= N or s >= N evaluate to False."""
        pub_key = _scalar_mul(12345, P256_G)
        assert pub_key is not None
        msg = b"message to verify"

        sig_rN = der_encode_signature(P256_N, 1)
        assert verify_ecdsa_p256_signature(pub_key, msg, sig_rN) is False

        sig_sN = der_encode_signature(1, P256_N)
        assert verify_ecdsa_p256_signature(pub_key, msg, sig_sN) is False

    def test_ecdsa_point_off_curve_and_infinity_rejected(self):
        """Points not satisfying y^2 = x^3 - 3x + b (mod p) or (0,0) evaluate to False."""
        msg = b"message to verify"
        dummy_sig = der_encode_signature(1, 1)

        # Off-curve point
        assert verify_ecdsa_p256_signature((123, 456), msg, dummy_sig) is False
        # Point at infinity
        assert verify_ecdsa_p256_signature((0, 0), msg, dummy_sig) is False


