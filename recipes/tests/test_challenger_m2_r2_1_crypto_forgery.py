@pytest.mark.django_db
class TestAntiRollbackCounterHardening:
    """Verify monotonic counter enforcement and clone detection."""

    def test_sign_count_regression_raises_403_and_preserves_db(self, crypto_user_setup):
        """Counter regression (sign_count < stored) returns strict HTTP 403 and leaves DB untouched."""
        cred = crypto_user_setup["credential"]
        cred.sign_count = 10
        cred.save()

        client = Client()
        opt_resp = client.post(reverse("auth:webauthn_login_options"), data=json.dumps({}), content_type="application/json")
        server_chal = opt_resp.json()["challenge"]

        payload = build_mock_assertion_payload(
            credential_id=cred.credential_id,
            challenge=server_chal,
            sign_count=9,  # Regression
            private_key=crypto_user_setup["private_key"],
        )

        resp = client.post(
            reverse("auth:webauthn_login_verify"),
            data=json.dumps({"credential": payload}),
            content_type="application/json",
        )
        assert resp.status_code == 403
        assert "rollback detected" in resp.json().get("error", "").lower()

        cred.refresh_from_db()
        assert cred.sign_count == 10

    def test_sign_count_duplicate_raises_403_and_preserves_db(self, crypto_user_setup):
        """Duplicate counter (sign_count == stored) returns strict HTTP 403."""
        cred = crypto_user_setup["credential"]
        cred.sign_count = 10
        cred.save()

        client = Client()
        opt_resp = client.post(reverse("auth:webauthn_login_options"), data=json.dumps({}), content_type="application/json")
        server_chal = opt_resp.json()["challenge"]

        payload = build_mock_assertion_payload(
            credential_id=cred.credential_id,
            challenge=server_chal,
            sign_count=10,  # Duplicate
            private_key=crypto_user_setup["private_key"],
        )

        resp = client.post(
            reverse("auth:webauthn_login_verify"),
            data=json.dumps({"credential": payload}),
            content_type="application/json",
        )
        assert resp.status_code == 403
        assert "rollback detected" in resp.json().get("error", "").lower()

        cred.refresh_from_db()
        assert cred.sign_count == 10

    def test_sign_count_monotonic_increment_succeeds(self, crypto_user_setup):
        """Monotonic counter increment (sign_count > stored) succeeds and updates database."""
        cred = crypto_user_setup["credential"]
        cred.sign_count = 10
        cred.save()

        client = Client()
        opt_resp = client.post(reverse("auth:webauthn_login_options"), data=json.dumps({}), content_type="application/json")
        server_chal = opt_resp.json()["challenge"]

        payload = build_mock_assertion_payload(
            credential_id=cred.credential_id,
            challenge=server_chal,
            sign_count=11,  # Increment
            private_key=crypto_user_setup["private_key"],
        )

        resp = client.post(
            reverse("auth:webauthn_login_verify"),
            data=json.dumps({"credential": payload}),
            content_type="application/json",
        )
        assert resp.status_code == 200
        assert resp.json()["success"] is True

        cred.refresh_from_db()
        assert cred.sign_count == 11
